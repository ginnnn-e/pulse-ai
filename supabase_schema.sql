-- 1. Enable pgvector extension for Retrieval-Augmented Generation (RAG)
create extension if not exists vector;

-- 2. Patients Table (Composite Primary Key: full_name + created_at for multiple clinic visits)
create table if not exists public.patients (
    full_name text not null,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    dob text,
    contact text,
    policy_number text,
    complaint text,
    status text default 'Registered',
    diagnosis text,
    prescription jsonb default '[]'::jsonb,
    medical_docs jsonb default '[]'::jsonb,
    visit_time timestamp with time zone default timezone('utc'::text, now()),
    consulted_at timestamp with time zone,
    consultation_time timestamp with time zone,
    primary key (full_name, created_at)
);

-- Add columns & migrate primary key safely if table already existed
alter table public.patients add column if not exists status text default 'Registered';
alter table public.patients add column if not exists diagnosis text;
alter table public.patients add column if not exists prescription jsonb default '[]'::jsonb;
alter table public.patients add column if not exists medical_docs jsonb default '[]'::jsonb;
alter table public.patients add column if not exists visit_time timestamp with time zone default timezone('utc'::text, now());
alter table public.patients add column if not exists consulted_at timestamp with time zone;
alter table public.patients add column if not exists consultation_time timestamp with time zone;

do $$
begin
    if exists (
        select 1
        from information_schema.table_constraints
        where table_schema = 'public'
          and table_name = 'patients'
          and constraint_type = 'PRIMARY KEY'
    ) then
        alter table public.patients drop constraint if exists patients_pkey;
    end if;
    alter table public.patients add constraint patients_pkey primary key (full_name, created_at);
exception
    when others then
        raise notice 'Primary key migration notice: %', sqlerrm;
end $$;

-- 3. Medical Documents Vector Store Table (Clinic-Wide Reference Documents)
drop function if exists match_medical_documents(vector,double precision,integer,text);
drop function if exists match_medical_documents(vector(768),double precision,integer,text);
drop function if exists match_medical_documents(vector(768),double precision,integer);
drop function if exists match_medical_documents;

drop table if exists public.medical_documents cascade;

create table public.medical_documents (
    id uuid default gen_random_uuid() primary key,   -- 1st column
    document_id text not null,                        -- 2nd column
    filename text not null,                           -- 3rd column
    document_url text,                                -- 4th column
    chunk_index integer default 0,                    -- 5th column
    content text not null,                            -- 6th column
    embedding vector(768),                            -- 7th column
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create index if not exists idx_medical_docs_doc_id on public.medical_documents(document_id);

-- Vector similarity search RPC function (Global clinic-wide search for all patients)
create or replace function match_medical_documents (
    query_embedding vector(768),
    match_threshold float default 0.15,
    match_count int default 5
)
returns table (
    id uuid,
    document_id text,
    filename text,
    content text,
    similarity float
)
language plpgsql
as $$
begin
    return query
    select
        md.id,
        md.document_id,
        md.filename,
        md.content,
        1 - (md.embedding <=> query_embedding) as similarity
    from public.medical_documents md
    where 1 - (md.embedding <=> query_embedding) > match_threshold
    order by md.embedding <=> query_embedding
    limit match_count;
end;
$$;

-- 4. Chatbot Analytics Logs Table
create table if not exists public.chat_logs (
    id bigint generated by default as identity primary key,
    patient_name text,
    question text not null,
    answer text not null,
    topic text default 'General Inquiry',
    sources jsonb default '[]'::jsonb,
    response_time_ms integer default 0,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 5. Row-Level Security (RLS) Policies for Public Access in Demo/Development
alter table public.patients enable row level security;
alter table public.medical_documents enable row level security;
alter table public.chat_logs enable row level security;

drop policy if exists "Allow public read/write on patients" on public.patients;
create policy "Allow public read/write on patients"
    on public.patients for all
    to anon, authenticated
    using (true)
    with check (true);

drop policy if exists "Allow public read/write on medical_documents" on public.medical_documents;
create policy "Allow public read/write on medical_documents"
    on public.medical_documents for all
    to anon, authenticated
    using (true)
    with check (true);

drop policy if exists "Allow public read/write on chat_logs" on public.chat_logs;
create policy "Allow public read/write on chat_logs"
    on public.chat_logs for all
    to anon, authenticated
    using (true)
    with check (true);

-- 6. Storage Bucket ('documents') & Public Upload Policy
insert into storage.buckets (id, name, public)
values ('documents', 'documents', true)
on conflict (id) do update set public = true;

drop policy if exists "Allow public uploads to documents bucket" on storage.objects;
create policy "Allow public uploads to documents bucket"
    on storage.objects for all
    to anon, authenticated
    using (bucket_id = 'documents')
    with check (bucket_id = 'documents');

